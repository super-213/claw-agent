#!/usr/bin/env python3
"""Generate macOS launchd and isolated Nginx configuration (no service changes)."""
import argparse
import json
from pathlib import Path
import plistlib


def nginx_quote(value):
    if any(c in value for c in '\n\r\x00$'):
        raise ValueError('Nginx 路径不能包含换行、NUL 或 $')
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def generate(app, runtime, output, python, nginx, web_port, api_port, secure):
    app, runtime, output = (Path(p).resolve() for p in (app, runtime, output))
    if not all(1024 <= p <= 65535 for p in (web_port, api_port)) or web_port == api_port:
        raise ValueError('网站和 API 必须使用两个不同的 1024-65535 端口')
    output.mkdir(parents=True, exist_ok=True)
    for name in ('client_temp', 'proxy_temp'):
        (runtime / name).mkdir(parents=True, exist_ok=True)
    logs = app / 'log' / 'mac'
    logs.mkdir(parents=True, exist_ok=True)
    # Reuse production routing/cache/upload/SSE behavior from the Linux deployment.
    server = (app / 'deploy' / 'claw-agent.conf').read_text()
    server = server.replace('listen 80 default_server;', f'listen 127.0.0.1:{web_port};')
    server = server.replace('    listen [::]:80 default_server;\n', '')
    server = server.replace('/var/www/claw-agent', nginx_quote(str(app / 'web-react' / 'dist')))
    server = server.replace('127.0.0.1:8000', f'127.0.0.1:{api_port}')
    # Only the local connector can reach this listener; preserve external HTTPS scheme.
    server = server.replace('X-Forwarded-Proto $scheme', 'X-Forwarded-Proto $origin_scheme')
    conf = f'''# Generated by deploy/mac.sh; independent of Homebrew's global nginx.conf.
worker_processes 1;
pid {nginx_quote(str(runtime / 'nginx.pid'))};
error_log {nginx_quote(str(logs / 'nginx-error.log'))};
events {{ worker_connections 1024; }}
http {{
    include {nginx_quote(str(runtime / 'mime.types'))};
    default_type application/octet-stream;
    access_log {nginx_quote(str(logs / 'nginx-access.log'))};
    client_body_temp_path {nginx_quote(str(runtime / 'client_temp'))};
    proxy_temp_path {nginx_quote(str(runtime / 'proxy_temp'))};
    map $http_x_forwarded_proto $origin_scheme {{ default $scheme; https https; }}
{server}
}}
'''
    (output / 'nginx.conf').write_text(conf)
    env = {'PATH': '/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin',
           'WEB_HOST': '127.0.0.1', 'PORT': str(api_port), 'PYTHONUNBUFFERED': '1',
           'AUTH_COOKIE_SECURE': 'true' if secure else 'false'}
    jobs = {
        'api': ([str(Path(python).absolute()), str(app / 'web_app.py')], env),
        'web': ([str(Path(nginx).absolute()), '-e', str(logs / 'nginx-error.log'), '-p', str(runtime) + '/', '-c',
                 str(runtime / 'nginx.conf'), '-g', 'daemon off;'], None),
    }
    for kind, (argv, environment) in jobs.items():
        label = f'com.claw-agent.{kind}'
        job = {'Label': label, 'ProgramArguments': argv, 'WorkingDirectory': str(app),
               'RunAtLoad': True, 'KeepAlive': True, 'ThrottleInterval': 5, 'Umask': 0o077,
               'StandardOutPath': str(logs / f'{kind}.log'),
               'StandardErrorPath': str(logs / f'{kind}.log')}
        if environment:
            job['EnvironmentVariables'] = environment
        with (output / f'{label}.plist').open('wb') as stream:
            plistlib.dump(job, stream)
    (output / 'config.json').write_text(json.dumps(
        {'web_port': web_port, 'api_port': api_port, 'secure_cookie': secure}, indent=2) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('app', 'runtime', 'output', 'python', 'nginx'):
        parser.add_argument('--' + name, required=True)
    parser.add_argument('--web-port', type=int, required=True)
    parser.add_argument('--api-port', type=int, required=True)
    parser.add_argument('--secure', action='store_true')
    args = vars(parser.parse_args())
    generate(**args)
